#!/usr/bin/env python3
"""Converts the Godot XR Tools glove models (CC0, by DigitalN8m4r3; see
GLOVE-MODEL-LICENSE.md) into src/xwa_remaster/vr_glove_mesh.h.

usage: gen_glove_mesh.py Hand_Glove_L.gltf Hand_Glove_R.gltf out.h

Per hand: the skin's joints (parent, rest translation/rotation/scale,
inverse bind matrix) and the skinned vertices (position, normal, 4 joints,
4 weights) with the triangle indices. Coordinates are the glTF's (+Y up,
metres), which is the controller aim frame the hands are attached to.
"""
import base64, json, struct, sys

def load(path):
    d = json.load(open(path))
    bufs = []
    for b in d['buffers']:
        uri = b['uri']
        assert uri.startswith('data:'), 'external buffers not supported'
        bufs.append(base64.b64decode(uri.split(',', 1)[1]))
    def acc(i):
        a = d['accessors'][i]
        v = d['bufferViews'][a['bufferView']]
        comp = {5126: ('f', 4), 5123: ('H', 2), 5121: ('B', 1), 5125: ('I', 4)}[a['componentType']]
        n = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4, 'MAT4': 16}[a['type']]
        stride = v.get('byteStride', comp[1] * n)
        base = v.get('byteOffset', 0) + a.get('byteOffset', 0)
        data = bufs[v['buffer']]
        out = []
        for k in range(a['count']):
            off = base + k * stride
            vals = struct.unpack_from('<%d%s' % (n, comp[0]), data, off)
            if a.get('normalized') and comp[0] in 'BH':
                vals = tuple(x / (255.0 if comp[0] == 'B' else 65535.0) for x in vals)
            out.append(vals)
        return out
    skin = d['skins'][0]
    joints = skin['joints']
    parent_of = {}
    for i, n in enumerate(d['nodes']):
        for c in n.get('children', []):
            parent_of[c] = i
    jinfo = []
    for j in joints:
        n = d['nodes'][j]
        p = parent_of.get(j)
        pj = joints.index(p) if p in joints else -1
        # Ancestors that are not joints (the armature) must be identity.
        q = p
        while q is not None and q not in joints:
            nn = d['nodes'][q]
            assert not any(k in nn for k in ('translation', 'rotation', 'scale', 'matrix')), nn
            q = parent_of.get(q)
        jinfo.append((n['name'], pj, n.get('translation', [0, 0, 0]), n.get('rotation', [0, 0, 0, 1]),
                      n.get('scale', [1, 1, 1])))
    ibm = acc(skin['inverseBindMatrices'])
    prim = d['meshes'][0]['primitives'][0]
    at = prim['attributes']
    pos = acc(at['POSITION']); nor = acc(at['NORMAL'])
    jo = acc(at['JOINTS_0']); we = acc(at['WEIGHTS_0'])
    idx = [i[0] for i in acc(prim['indices'])]
    return jinfo, ibm, pos, nor, jo, we, idx

def emit(out, tag, data):
    jinfo, ibm, pos, nor, jo, we, idx = data
    out.append('static const XwaVrGloveJoint k_glove_%s_joints[%d] = {' % (tag, len(jinfo)))
    for (name, pj, t, r, s), m in zip(jinfo, ibm):
        out.append('\t{ "%s", %d, { %.6ff, %.6ff, %.6ff }, { %.6ff, %.6ff, %.6ff, %.6ff }, { %.6ff, %.6ff, %.6ff },' %
                   (name, pj, *t, *r, *s))
        out.append('\t  { ' + ', '.join('%.7ff' % x for x in m) + ' } },')
    out.append('};')
    out.append('static const XwaVrGloveVertex k_glove_%s_vertices[%d] = {' % (tag, len(pos)))
    for p, n, j, w in zip(pos, nor, jo, we):
        sw = sum(w) or 1.0
        out.append('\t{ { %.5ff, %.5ff, %.5ff }, { %.4ff, %.4ff, %.4ff }, { %d, %d, %d, %d }, { %.4ff, %.4ff, %.4ff, %.4ff } },' %
                   (*p, *n, *j, *(x / sw for x in w)))
    out.append('};')
    out.append('static const uint16_t k_glove_%s_indices[%d] = {' % (tag, len(idx)))
    for k in range(0, len(idx), 24):
        out.append('\t' + ', '.join(str(x) for x in idx[k:k + 24]) + ',')
    out.append('};')

left, right = load(sys.argv[1]), load(sys.argv[2])
out = ['/* Generated by tools/vr/gen_glove_mesh.py from the Godot XR Tools glove',
       ' * models (CC0 1.0, DigitalN8m4r3; tools/vr/GLOVE-MODEL-LICENSE.md). */',
       '#ifndef XWA_REMASTER_VR_GLOVE_MESH_H', '#define XWA_REMASTER_VR_GLOVE_MESH_H', '',
       '#include <stdint.h>', '',
       'typedef struct XwaVrGloveJoint {', '\tconst char* name;', '\tint parent;',
       '\tfloat t[3], r[4], s[3]; /* rest pose, r = x y z w */',
       '\tfloat inverse_bind[16]; /* column-major */', '} XwaVrGloveJoint;', '',
       'typedef struct XwaVrGloveVertex {', '\tfloat pos[3], normal[3];', '\tuint8_t joints[4];',
       '\tfloat weights[4];', '} XwaVrGloveVertex;', '',
       '#define XWA_VR_GLOVE_JOINTS %d' % len(right[0]),
       '#define XWA_VR_GLOVE_L_VERTICES %d' % len(left[2]), '#define XWA_VR_GLOVE_R_VERTICES %d' % len(right[2]),
       '#define XWA_VR_GLOVE_L_INDICES %d' % len(left[6]), '#define XWA_VR_GLOVE_R_INDICES %d' % len(right[6]), '']
assert len(left[0]) == len(right[0])
emit(out, 'l', left)
emit(out, 'r', right)
out += ['', '#endif', '']
open(sys.argv[3], 'w').write('\n'.join(out))
print('joints', len(right[0]), 'verts', len(left[2]), len(right[2]), 'indices', len(left[6]), len(right[6]))
