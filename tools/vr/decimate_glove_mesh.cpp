// Decimates the glove meshes in src/xwa_remaster/vr_glove_mesh.h (written by
// gen_glove_mesh.py) with meshoptimizer's simplifier, keeping the skeleton
// and each kept vertex's skin weights as they are (the simplifier only
// removes vertices, it never moves them).
//
// build: c++ -O2 -std=c++17 -I<meshoptimizer>/src decimate_glove_mesh.cpp \
//            <meshoptimizer>/src/*.cpp -o decimate_glove_mesh
// usage: decimate_glove_mesh <ratio 0..1> <full mesh header> > vr_glove_mesh.h
//        (the header is compiled in: build against the full-detail one)
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

#include "meshoptimizer.h"

#include GLOVE_HEADER

struct Out {
	std::vector<XwaVrGloveVertex> v;
	std::vector<uint16_t> idx;
};

static Out decimate(const XwaVrGloveVertex* v, int vn, const uint16_t* idx, int in, float ratio) {
	std::vector<float> pos(vn * 3), nrm(vn * 3);
	for (int i = 0; i < vn; ++i) {
		memcpy(&pos[i * 3], v[i].pos, sizeof v[i].pos);
		memcpy(&nrm[i * 3], v[i].normal, sizeof v[i].normal);
	}
	std::vector<unsigned int> src(idx, idx + in), dst(in);
	const float weights[3] = { 0.5f, 0.5f, 0.5f };
	float err = 0.0f;
	size_t target = (size_t)(in * ratio) / 3 * 3;
	size_t n = meshopt_simplifyWithAttributes(dst.data(), src.data(), in, pos.data(), vn, 12, nrm.data(), 12, weights,
											  3, nullptr, target, 0.05f, 0, &err);
	dst.resize(n);
	meshopt_optimizeVertexCache(dst.data(), dst.data(), n, vn);
	std::vector<unsigned int> remap(vn);
	size_t used = meshopt_optimizeVertexFetchRemap(remap.data(), dst.data(), n, vn);
	Out o;
	o.v.resize(used);
	for (int i = 0; i < vn; ++i) {
		if (remap[i] != ~0u) {
			o.v[remap[i]] = v[i];
		}
	}
	for (size_t k = 0; k < n; ++k) {
		o.idx.push_back((uint16_t)remap[dst[k]]);
	}
	fprintf(stderr, "%d -> %zu vertices, %d -> %zu triangles (error %.4f)\n", vn, used, in / 3, n / 3, err);
	return o;
}

static void emit_joints(const char* name, const XwaVrGloveJoint* j) {
	printf("static const XwaVrGloveJoint %s[%d] = {\n", name, XWA_VR_GLOVE_JOINTS);
	for (int i = 0; i < XWA_VR_GLOVE_JOINTS; ++i) {
		printf("\t{ \"%s\", %d, { %.6ff, %.6ff, %.6ff }, { %.6ff, %.6ff, %.6ff, %.6ff }, { %.6ff, %.6ff, %.6ff },\n\t  { ",
			   j[i].name, j[i].parent, j[i].t[0], j[i].t[1], j[i].t[2], j[i].r[0], j[i].r[1], j[i].r[2], j[i].r[3],
			   j[i].s[0], j[i].s[1], j[i].s[2]);
		for (int k = 0; k < 16; ++k) {
			printf("%.7ff%s", j[i].inverse_bind[k], k < 15 ? ", " : "");
		}
		printf(" } },\n");
	}
	printf("};\n\n");
}

static void emit_mesh(const char* vname, const char* iname, const Out& o) {
	printf("static const XwaVrGloveVertex %s[%zu] = {\n", vname, o.v.size());
	for (const XwaVrGloveVertex& v : o.v) {
		printf("\t{ { %.5ff, %.5ff, %.5ff }, { %.4ff, %.4ff, %.4ff }, { %u, %u, %u, %u }, { %.4ff, %.4ff, %.4ff, %.4ff } },\n",
			   v.pos[0], v.pos[1], v.pos[2], v.normal[0], v.normal[1], v.normal[2], v.joints[0], v.joints[1],
			   v.joints[2], v.joints[3], v.weights[0], v.weights[1], v.weights[2], v.weights[3]);
	}
	printf("};\n\nstatic const uint16_t %s[%zu] = {\n", iname, o.idx.size());
	for (size_t k = 0; k < o.idx.size(); ++k) {
		printf("%s%u,%s", k % 24 == 0 ? "\t" : "", o.idx[k], k % 24 == 23 || k + 1 == o.idx.size() ? "\n" : " ");
	}
	printf("};\n\n");
}

int main(int argc, char** argv) {
	const float ratio = argc > 1 ? (float)atof(argv[1]) : 0.4f;
	Out l = decimate(k_glove_l_vertices, XWA_VR_GLOVE_L_VERTICES, k_glove_l_indices, XWA_VR_GLOVE_L_INDICES, ratio);
	Out r = decimate(k_glove_r_vertices, XWA_VR_GLOVE_R_VERTICES, k_glove_r_indices, XWA_VR_GLOVE_R_INDICES, ratio);
	printf("/* Generated by tools/vr/gen_glove_mesh.py from the Godot XR Tools glove\n"
		   " * models (CC0 1.0, DigitalN8m4r3; tools/vr/GLOVE-MODEL-LICENSE.md), then\n"
		   " * decimated to %.0f%% of the triangles by tools/vr/decimate_glove_mesh.cpp\n"
		   " * (meshoptimizer; the kept vertices and their skin weights unchanged). */\n",
		   ratio * 100.0f);
	printf("#ifndef XWA_REMASTER_VR_GLOVE_MESH_H\n#define XWA_REMASTER_VR_GLOVE_MESH_H\n\n#include <stdint.h>\n\n");
	printf("typedef struct XwaVrGloveJoint {\n\tconst char* name;\n\tint parent;\n\tfloat t[3], r[4], s[3]; /* rest pose, r = "
		   "x y z w */\n\tfloat inverse_bind[16]; /* column-major */\n} XwaVrGloveJoint;\n\n");
	printf("typedef struct XwaVrGloveVertex {\n\tfloat pos[3], normal[3];\n\tuint8_t joints[4];\n\tfloat weights[4];\n} "
		   "XwaVrGloveVertex;\n\n");
	printf("#define XWA_VR_GLOVE_JOINTS %d\n", XWA_VR_GLOVE_JOINTS);
	printf("#define XWA_VR_GLOVE_L_VERTICES %zu\n#define XWA_VR_GLOVE_R_VERTICES %zu\n", l.v.size(), r.v.size());
	printf("#define XWA_VR_GLOVE_L_INDICES %zu\n#define XWA_VR_GLOVE_R_INDICES %zu\n\n", l.idx.size(), r.idx.size());
	emit_joints("k_glove_l_joints", k_glove_l_joints);
	emit_mesh("k_glove_l_vertices", "k_glove_l_indices", l);
	emit_joints("k_glove_r_joints", k_glove_r_joints);
	emit_mesh("k_glove_r_vertices", "k_glove_r_indices", r);
	printf("#endif\n");
	return 0;
}
