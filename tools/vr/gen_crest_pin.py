#!/usr/bin/env python3
"""Generates the VR glove's crest pin mesh (src/xwa_remaster/vr_crest_pin.h).

The family crest is modelled from simple shapes traced from a reference
image (1536x1024 px): a ring, three bars on each side and the bird in the
middle, each extruded into a thin metal relief. Output: triangle list of
(position, normal) in metres, pin-local frame: +X right, +Y up, +Z out of
the glove. The ring is ~14 mm across.
"""
import math, sys

PX = 0.014 / 880.0          # metres per reference pixel (ring diameter 880 px)
CX, CY = 768.0, 498.0       # ring centre in the reference image

def to_m(x, y):
    return ((x - CX) * PX, (CY - y) * PX)

tris = []  # (p0, p1, p2, n)

def add_tri(a, b, c, n):
    tris.append((a, b, c, n))

def extrude(poly, z0, z1):
    """poly: list of (x, y) metres, counter-clockwise. Top cap by ear
    clipping, side walls, no bottom (it sits on the glove)."""
    pts = poly[:]
    # Ear clipping.
    idx = list(range(len(pts)))
    def area2(i, j, k):
        (ax, ay), (bx, by), (cx, cy) = pts[i], pts[j], pts[k]
        return (bx - ax) * (cy - ay) - (by - ay) * (cx - ax)
    def inside(p, a, b, c):
        def s(p1, p2, p3):
            return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
        d1, d2, d3 = s(p, a, b), s(p, b, c), s(p, c, a)
        neg = d1 < 0 or d2 < 0 or d3 < 0
        pos = d1 > 0 or d2 > 0 or d3 > 0
        return not (neg and pos)
    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        n = len(idx)
        for k in range(n):
            i, j, l = idx[(k - 1) % n], idx[k], idx[(k + 1) % n]
            if area2(i, j, l) <= 0:
                continue
            if any(inside(pts[m], pts[i], pts[j], pts[l]) for m in idx if m not in (i, j, l)):
                continue
            add_tri((*pts[i], z1), (*pts[j], z1), (*pts[l], z1), (0, 0, 1))
            idx.pop(k)
            break
        else:
            sys.exit("ear clipping failed")
    add_tri((*pts[idx[0]], z1), (*pts[idx[1]], z1), (*pts[idx[2]], z1), (0, 0, 1))
    # Walls (outward normals for a CCW polygon).
    for k in range(len(pts)):
        (ax, ay), (bx, by) = pts[k], pts[(k + 1) % len(pts)]
        dx, dy = bx - ax, by - ay
        l = math.hypot(dx, dy) or 1.0
        n = (dy / l, -dx / l, 0.0)
        add_tri((ax, ay, z0), (bx, by, z0), (bx, by, z1), n)
        add_tri((ax, ay, z0), (bx, by, z1), (ax, ay, z1), n)

def ccw(poly):
    a = sum(poly[i][0] * poly[(i + 1) % len(poly)][1] - poly[(i + 1) % len(poly)][0] * poly[i][1]
            for i in range(len(poly)))
    return poly if a > 0 else poly[::-1]

def rect(x0, y0, x1, y1):
    return ccw([to_m(x0, y0), to_m(x1, y0), to_m(x1, y1), to_m(x0, y1)])

Z0, Z_RING, Z_BAR, Z_BIRD = 0.0, 0.0010, 0.0013, 0.0017

# Ring: annulus as quads (top + both walls).
R_OUT, R_IN, SEG = 445 * PX, 412 * PX, 48
for s in range(SEG):
    a0, a1 = 2 * math.pi * s / SEG, 2 * math.pi * (s + 1) / SEG
    o0 = (R_OUT * math.cos(a0), R_OUT * math.sin(a0)); o1 = (R_OUT * math.cos(a1), R_OUT * math.sin(a1))
    i0 = (R_IN * math.cos(a0), R_IN * math.sin(a0)); i1 = (R_IN * math.cos(a1), R_IN * math.sin(a1))
    add_tri((*i0, Z_RING), (*o0, Z_RING), (*o1, Z_RING), (0, 0, 1))
    add_tri((*i0, Z_RING), (*o1, Z_RING), (*i1, Z_RING), (0, 0, 1))
    am = 0.5 * (a0 + a1)
    no = (math.cos(am), math.sin(am), 0.0)
    add_tri((*o0, Z0), (*o1, Z0), (*o1, Z_RING), no)
    add_tri((*o0, Z0), (*o1, Z_RING), (*o0, Z_RING), no)
    ni = (-no[0], -no[1], 0.0)
    add_tri((*i1, Z0), (*i0, Z0), (*i0, Z_RING), ni)
    add_tri((*i1, Z0), (*i0, Z_RING), (*i1, Z_RING), ni)

# Bars (left and right of the bird).
for (y0, y1) in ((404, 438), (474, 532), (600, 668)):
    extrude(rect(237, y0, 640, y1), Z0, Z_BAR)
    extrude(rect(930, y0, 1298, y1), Z0, Z_BAR)

# Bird: body with the notched tail, neck, beak and crest (traced outline).
bird = [(605, 830), (768, 700), (945, 830), (945, 440), (860, 345), (850, 230), (868, 142),
        (790, 205), (735, 225), (650, 262), (590, 285), (668, 288), (720, 268),
        (690, 345), (640, 400), (605, 445)]
extrude(ccw([to_m(x, y) for x, y in bird]), Z0, Z_BIRD)

out = ["/* Generated by tools/vr/gen_crest_pin.py: the family crest pin of the",
       " * VR gloves. Triangle list, position xyz + normal xyz, metres, pin-local",
       " * frame (+X right, +Y up, +Z out of the glove). */",
       "#ifndef XWA_REMASTER_VR_CREST_PIN_H", "#define XWA_REMASTER_VR_CREST_PIN_H", "",
       "#define XWA_VR_CREST_PIN_VERTEX_COUNT %d" % (3 * len(tris)), "",
       "static const float k_vr_crest_pin[XWA_VR_CREST_PIN_VERTEX_COUNT][6] = {"]
for a, b, c, n in tris:
    for p in (a, b, c):
        out.append("\t{ %.6ff, %.6ff, %.6ff, %.4ff, %.4ff, %.4ff }," % (p[0], p[1], p[2], n[0], n[1], n[2]))
out += ["};", "", "#endif", ""]
open(sys.argv[1], "w").write("\n".join(out))
print("triangles", len(tris))
